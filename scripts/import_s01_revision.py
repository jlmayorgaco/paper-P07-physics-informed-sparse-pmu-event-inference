"""Import audited successor controls without touching the C01 pipeline."""
from pathlib import Path
import hashlib
import json

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT.parent/'SGSMA26-Physics-Informed-AD/experiments/PAPER_SUBMISSION_S01'
FROZEN=ROOT/'generated/frozen/submission_s01_controls_20261031'


def sha(data): return hashlib.sha256(data).hexdigest()


def main():
    files={
      'single_state_evaluation.json':'run/single_state_h04/EVALUATION.json',
      'single_state_plan.json':'protocol/SINGLE_STATE_PLAN.json',
      'single_state_sources.json':'checks/SINGLE_STATE_EXECUTION_SOURCES.json',
      'legacy_raw_evaluation.json':'run/legacy_continuous/EVALUATION.json',
      'cyber_evaluation.json':'run/cyber_composition_v2/EVALUATION.json',
      'cyber_plan.json':'protocol/CYBER_PLAN.json',
      'historical_parity_evaluation.json':'run/legacy_historical/EVALUATION.json',
      'physical_raw_startup.json':'run/raw_physical_prefix/RESULT.json',
      'physical_raw_prefix_diagnostic.json':'run/raw_prefix_review_20261031/attempt03/DIAGNOSTIC.json',
      'physical_raw_prefix_shape.json':'run/raw_prefix_review_20261031/shape_followup/SHAPE.json',
      'successor_metrics.py':'evaluation/metrics.py',
      'raw_audit_validation.json':'evaluation/RAW_AUDIT_VALIDATION.json',
    }
    FROZEN.mkdir(parents=True,exist_ok=True)
    manifest={}
    for destination,relative in files.items():
        source=SOURCE/relative
        data=source.read_bytes()
        target=FROZEN/destination
        if target.exists() and target.read_bytes()!=data:
            raise ValueError(f'Frozen artifact differs: {destination}; create a successor import')
        if not target.exists(): target.write_bytes(data)
        manifest[destination]=dict(source=str(source),sha256=sha(data))
    (FROZEN/'MANIFEST.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    physical=json.loads((FROZEN/'single_state_evaluation.json').read_text())
    raw=json.loads((FROZEN/'legacy_raw_evaluation.json').read_text())['results']
    cyber=json.loads((FROZEN/'cyber_evaluation.json').read_text())
    rows={r['method']:r for r in physical['summary']}
    values={}
    for prefix,method in [('SSSimple','SINGLE_STATE_SHORT_GLR'),('SSMix','R11_COMMON_CLOCK'),('SSNom','R11_NOMINAL_COMMON_CLOCK')]:
        row=rows[method]
        for suffix,key in [('Timely','timely_joint'),('Total','intended_events'),('Extras','extras'),('Premature','premature_restorations'),('Missing','restoration_missing'),('Orphan','orphan_restorations')]:
            values[prefix+suffix]=str(row[key])
    values.update(SSNormalSeconds=str(int(rows['SINGLE_STATE_SHORT_GLR']['normal_exposure_s'])),
        SSRawWindows=str(raw['windows']),SSRawAvailable=str(raw['available_windows']),
        SSRawPositive=str(raw['window_native_binary']['recall']['total']),
        SSRawDetected=str(raw['window_native_binary']['tp']),SSRawFalse=str(raw['window_native_binary']['fp']),
        SSRawNormal=str(raw['window_native_binary']['false_positive_fraction']['total']),
        SSRawPhysicalCorrect=str(raw['window_composed_physical_family_sets']['any_target_hit_over_all_positive']['correct']),
        SSRawPhysicalTotal=str(raw['window_composed_physical_family_sets']['positive_windows']),
        SSMissingCorrect=str(cyber['causal_pointwise_availability']['report_binary']['tp']),
        SSMissingTotal=str(cyber['causal_pointwise_availability']['report_binary']['recall']['total']),
        SSCorruptLocated=str(cyber['completed_interval_components']['corrupt']['any_target_hit_over_all_positive']['correct']),
        SSCorruptTotal=str(cyber['completed_interval_components']['corrupt']['positive_windows']))
    macros='% Generated by scripts/import_s01_revision.py; see frozen manifest.\n'
    macros+='\n'.join('\\newcommand{\\'+key+'}{'+value+'}' for key,value in values.items())+'\n'
    (ROOT/'generated/submission_s01_macros.tex').write_text(macros,encoding='utf-8')
    table=r'''% Generated from sealed predictions and successor metrics.
\begin{table}[t]\centering
\caption{Open-development comparison with the same six-report publication clock. All 54 event replays are retained. Threshold score semantics differ; this does not establish equal false-alarm operating points. Missing closure includes missed events.}
\label{tab:single-state-control}
\small\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrrrr}\hline
Procedure & Timely & Extras & Early OFF & No OFF\\\hline
'''
    for label,method in [('Single state, short GLR','SINGLE_STATE_SHORT_GLR'),('Nominal history bank','R11_NOMINAL_COMMON_CLOCK'),('Five-model history bank','R11_COMMON_CLOCK')]:
        r=rows[method]
        table+=f"{label} & {r['timely_joint']}/{r['intended_events']} & {r['extras']} & {r['premature_restorations']} & {r['restoration_missing']} "+r'\\'+'\n'
    table+=r'''\hline\end{tabular}
\end{table}
'''
    (ROOT/'tables/generated/single_state_control.tex').write_text(table,encoding='utf-8')
    print(json.dumps({'frozen_files':len(files),'source_predictions_altered':False,'C01_accessed':False},indent=2))


if __name__=='__main__': main()
