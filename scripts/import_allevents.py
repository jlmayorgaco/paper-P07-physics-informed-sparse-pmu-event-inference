"""Import the all-event attribution ledgers (competition record and sealed simulated cohort).

Reads the science-repository ledgers and writes
  generated/revision_allevents_macros.tex
  tables/generated/allevents_raw.tex
  tables/generated/allevents_sim.tex
No numbers are typed by hand; every table cell comes from a scored ledger entry.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCI = ROOT.parent / "SGSMA26-Physics-Informed-AD" / "experiments"
EXP = SCI / "PAPER_ALLEVENTS_V1"
RAW = EXP / "run/raw_ledger"
SIM = EXP / "run/sim_ledger"
BANK = SCI / "PAPER_CALIBRATION_B01/run/TEST_EVALUATION.json"
BS = chr(92)


def raw_row(tag: str) -> dict:
    s = json.loads((RAW / tag / "SCORE.json").read_text())
    ev = s["events"]
    return dict(det=sum(e["detected"] for e in ev), cls=sum(e["class_correct"] for e in ev),
                top1=sum(bool(e["top1"]) for e in ev), n=len(ev), f1=s["task1"]["f1"],
                fa=s["task1"]["false_alarms_per_min"], macro=s["task2"]["macro_f1"], wf1=s["task2"]["weighted_f1"])


def sim_row(tag: str) -> dict:
    s = json.loads((SIM / tag / "SCORE.json").read_text())["summary"]
    recs = json.loads((SIM / tag / "SCORE.json").read_text())["records"]
    fa = sum(r["extras"] for r in recs if not r["rows"])
    return dict(det=s["detected"], n=s["events"], cls=s["class_ok"], top1=s["top1"],
                line_det=s["line"]["detected"], line_top1=s["line"]["top1"],
                load_det=s["load"]["detected"], load_top1=s["load"]["top1"], fa=fa)


def bank_row() -> dict:
    import csv
    a = json.loads(BANK.read_text())["arms"]["A0"]
    ev = [r for r in csv.DictReader((BANK.parent / "results/EVENTS.csv").open()) if r["arm"] == "A0"]
    fam = lambda f, key: sum(r[key] == "True" for r in ev if r["family"] == f)
    return dict(det=a["detected"], n=a["events"], top1=a["joint"], line_top1=fam("line", "joint"),
                load_det=fam("load", "detected"), load_top1=fam("load", "joint"), fa=a["false_alarms"])


def main() -> None:
    raw = {k: raw_row(t) for k, t in (("sub", "iter000_legacy_hackathon"), ("one", "iter006_reversal_off"),
                                       ("two", "iter008_v2_v1_closure"))}
    sim = {k: sim_row(t) for k, t in (("one", "v1_TEST_open"), ("two", "v2_TEST_open"), ("twocat", "v2_TEST_bank"))}
    nraw = len([p for p in RAW.iterdir() if p.is_dir()]) - 1          # iterations after the submitted system
    m = {
        "AERawIter": str(nraw), "AERawIterOne": "6",
        "AERawTwoFone": f"{raw['two']['f1']:.3f}", "AERawTwoFA": f"{raw['two']['fa']:.2f}",
        "AERawTwoMacro": f"{raw['two']['macro']:.2f}", "AERawSubFone": f"{raw['sub']['f1']:.2f}",
        "AERawSubTopone": str(raw['sub']['top1']), "AERawSubMacro": f"{raw['sub']['macro']:.2f}",
        "AESimTwoDet": str(sim['two']['det']), "AESimTwoTopone": str(sim['two']['top1']),
        "AESimCatTopone": str(sim['twocat']['top1']), "AESimOneDet": str(sim['one']['det']),
        "AESimOneTopone": str(sim['one']['top1']),
        "AESimLineDet": str(sim['two']['line_det']), "AESimLoadDet": str(sim['two']['load_det']),
        "AESimCatLineTopone": str(sim['twocat']['line_top1']), "AESimCatLoadTopone": str(sim['twocat']['load_top1']),
        "AESimLineTopone": str(sim['two']['line_top1']),
        "AEWallTwo": f"{json.loads((SIM / 'v2_TEST_open/PREDICTION_SEAL.json').read_text())['wall_s']:.0f}",
        "AEWallBankH": f"{json.loads(BANK.read_text())['arms']['A0']['inference_wall_seconds'] / 3600:.1f}",
        "AEWallRaw": f"{json.loads((RAW / 'iter008_v2_v1_closure/CHANGE.json').read_text())['wall_s']:.0f}",
    }
    (ROOT / "generated/revision_allevents_macros.tex").write_text(
        "% generated by scripts/import_allevents.py\n" + "".join(f"{BS}newcommand{{{BS}{k}}}{{{v}}}\n" for k, v in m.items()))
    mr = BS + "midrule"
    lines = [f"{BS}begin{{table}}[t]{BS}centering{BS}footnotesize",
             f"{BS}caption{{All event types on the competition record (12 guide-defined labels: one fault, one line outage, one generation change, one load change, four dropouts, three corruptions and one simultaneous missing-PMU/generation event). The composite label is scored separately from the coincident generation label. Report-level scores follow the competition guide; false alarms are episodes outside every label.}}",
             f"{BS}label{{tab:allevents-raw}}{BS}setlength{{{BS}tabcolsep}}{{3.2pt}}",
             f"{BS}begin{{tabular}}{{lccccc}}{BS}toprule",
             f"Method & Class & Top-1 & F1 & FA/min & Macro-F1 {BS}{BS}", mr]
    names = {"sub": "Submitted system", "one": "Attributor I", "two": "Attributor II"}
    for k in ("sub", "one", "two"):
        r = raw[k]
        lines.append(f"{names[k]} & {r['cls']}/{r['n']} & {r['top1']}/{r['n']} & {r['f1']:.3f} & {r['fa']:.2f} & {r['macro']:.2f} {BS}{BS}")
    lines += [f"{BS}bottomrule{BS}end{{tabular}}{BS}end{{table}}"]
    (ROOT / "tables/generated/allevents_raw.tex").write_text("\n".join(lines) + "\n")
    lines = [f"{BS}begin{{table}}[t]{BS}centering{BS}footnotesize",
             f"{BS}caption{{Sealed simulated cohort, evaluated once: 72 load and line pulses (2--5\\,s, six per record) in 12 records, and 12 normal records (2\\,h). Top-1 counts events with the right family and exact source. The dynamic bank uses the plant model and an 18-source catalog; the open search ranks all 39 buses and 46 branches.}}",
             f"{BS}label{{tab:allevents-sim}}{BS}setlength{{{BS}tabcolsep}}{{2.6pt}}",
             f"{BS}begin{{tabular}}{{lcccccc}}{BS}toprule",
             f"Method & Detected & Top-1 & Lines & Loads & Loads & Normal {BS}{BS}",
             f" & & & Top-1 & detected & Top-1 & alarms {BS}{BS}", mr]
    rows = (("Attributor I, open", sim["one"]), ("Attributor II, open", sim["two"]), ("Attributor II, catalog", sim["twocat"]))
    for nm, r in rows:
        lines.append(f"{nm} & {r['det']}/72 & {r['top1']}/72 & {r['line_top1']}/36 & {r['load_det']}/36 & {r['load_top1']}/36 & {r['fa']} {BS}{BS}")
    b = bank_row()
    lines.append(f"Dynamic bank, catalog & {b['det']}/{b['n']} & {b['top1']}/{b['n']} & {b['line_top1']}/36 & {b['load_det']}/36 & {b['load_top1']}/36 & {b['fa']} {BS}{BS}")
    lines += [f"{BS}bottomrule{BS}end{{tabular}}{BS}end{{table}}"]
    (ROOT / "tables/generated/allevents_sim.tex").write_text("\n".join(lines) + "\n")
    print(json.dumps(dict(raw=raw, sim=sim, macros=m), indent=1, default=float))


if __name__ == "__main__":
    main()
