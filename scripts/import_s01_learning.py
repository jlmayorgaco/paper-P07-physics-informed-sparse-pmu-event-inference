"""Import completed grouped-SIM learning and received-report integrity latency."""
from pathlib import Path
import csv
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'SGSMA26-Physics-Informed-AD/experiments/PAPER_SUBMISSION_S01'
FROZEN = ROOT / 'generated/frozen/submission_s01_learning_20261031'


def main():
    files = {
        'ml_plan.json': 'protocol/ML_PLAN.json',
        'split.json': 'protocol/DEVELOPMENT_SPLIT.json',
        'model_freeze.json': 'ml/MODEL_FREEZE.json',
        'holdout_complete.json': 'ml/HOLDOUT_COMPLETE.json',
        'holdout_summary.json': 'ml/metrics/development_holdout_30/SHORT/SUMMARY.json',
        'holdout_events.csv': 'ml/metrics/development_holdout_30/SHORT/EVENTS.csv',
        'validation_events.csv': 'ml/metrics/validation_14/SHORT/EVENTS.csv',
        'missing_latency.json': 'run/cyber_composition_v2/MISSING_LATENCY_COMPARISON.json',
        'missing_latency_protocol.json': 'evaluation/MISSING_LATENCY_PROTOCOL.json',
        'missing_latency_validation.json': 'evaluation/MISSING_LATENCY_VALIDATION.json',
    }
    FROZEN.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name, relative in files.items():
        source = SOURCE / relative
        data = source.read_bytes()
        target = FROZEN / name
        if target.exists() and target.read_bytes() != data:
            raise ValueError(f'Changed frozen input {name}; use a successor namespace')
        if not target.exists():
            target.write_bytes(data)
        manifest[name] = dict(source=str(source), sha256=hashlib.sha256(data).hexdigest())
    (FROZEN / 'MANIFEST.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    read = lambda name: json.loads((FROZEN / name).read_text(encoding='utf-8'))
    freeze = read('model_freeze.json')
    selected = freeze['selected_variant']
    assert selected == 'SHORT'
    validation = {row['variant']: row for row in freeze['validation']}
    holdout = read('holdout_summary.json')
    split = read('split.json')['partitions']
    latency = read('missing_latency.json')
    values = {}
    for prefix, name in [('MLTrain', 'train_56'), ('MLVal', 'validation_14'), ('MLHold', 'development_holdout_30')]:
        values[prefix + 'Groups'] = split[name]['groups']
        values[prefix + 'Records'] = split[name]['observed_records']
    for prefix, row in [('MLBaseVal', validation['BASELINE']), ('MLShortVal', validation['SHORT']), ('MLHold', holdout)]:
        for suffix, key in [('Timely', 'joint_before_off'), ('Events', 'events'), ('Load', 'load_before_off'), ('Line', 'line_before_off'), ('Extras', 'extras')]:
            values[prefix + suffix] = row[key]
    for prefix, filename in [('MLVal', 'validation_events.csv'), ('MLHold', 'holdout_events.csv')]:
        with (FROZEN / filename).open(newline='', encoding='utf-8') as handle:
            events = list(csv.DictReader(handle))
        for family in ('load', 'line'):
            values[prefix + family.title() + 'Total'] = sum(row['family'] == family for row in events)
        assert len(events) == (holdout if prefix == 'MLHold' else validation['SHORT'])['events']
    values['MLHoldNormalSeconds'] = int(holdout['normal_exposure_s'])
    values['MLHoldNormalAlarms'] = holdout['normal_FA']
    values['MissingEpisodes'] = latency['native_zip']['intended_intervals']
    values['MissingLegacyDelay'] = f"{latency['native_zip']['restricted_first_source_delay_mean_s']:.2f}"
    values['MissingImmediateDelay'] = f"{latency['immediate_availability_v2']['restricted_first_source_delay_mean_s']:.0f}"
    text = '% Generated from immutable S01 learning and latency artifacts.\n'
    text += ''.join('\\newcommand{\\' + key + '}{' + str(value) + '}\n' for key, value in values.items())
    (ROOT / 'generated/submission_s01_learning_macros.tex').write_text(text, encoding='utf-8')
    table = r'''% Generated by import_s01_learning.py; unequal cohorts are not a paired contrast.
\begin{table}[t]\centering
\caption{Grouped SIM development. SHORT is selected only on validation; the reserved 30\% is evaluated once. These cohorts are distinct from H04.}
\label{tab:grouped-learning}
\small\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrr}\hline
Variant and partition & Load & Line & Extras\\\hline
'''
    for label, row, den_prefix in [('Baseline, validation', validation['BASELINE'], 'MLVal'), ('SHORT, validation', validation['SHORT'], 'MLVal'), ('SHORT, reserved', holdout, 'MLHold')]:
        table += f"{label} & {row['load_before_off']}/{values[den_prefix+'LoadTotal']} & {row['line_before_off']}/{values[den_prefix+'LineTotal']} & {row['extras']} " + r'\\' + '\n'
    table += '\\hline\\end{tabular}\n\\end{table}\n'
    (ROOT / 'tables/generated/grouped_learning.tex').write_text(table, encoding='utf-8')
    print(json.dumps(dict(frozen_files=len(files), selected=selected, holdout_joint=holdout['joint_before_off'], source_predictions_altered=False)))


if __name__ == '__main__':
    main()
