"""Import the second-plant transfer study (experiments/second_plant/results.json) and the original-cohort rows.
Writes generated/revision_secondplant_macros.tex and tables/generated/second_plant.tex.  No number typed by hand."""
from __future__ import annotations
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
BS = chr(92); EV_H = 12 * 120 / 3600


def main() -> None:
    r = json.loads((ROOT / "experiments/second_plant/results.json").read_text())["results"]
    base = json.loads((ROOT / "experiments/fair_baselines/results/BASELINES_ALL.json").read_text())["results"]
    rows = []
    s = r["static"]["summary"]
    f01 = None
    # original-cohort static row comes from the sealed ledger already imported by the baselines table
    import re
    led = (ROOT.parent / "SGSMA26-Physics-Informed-AD/experiments/PAPER_ALLEVENTS_V1/run/sim_ledger/LEDGER.md").read_text(encoding="utf-8")
    m = re.search(r"\| v2_TEST_bank \|[^|]*\| (\d+)/72 \| (\d+) \| (\d+) \| (\d+) \| (\d+)/(\d+) \| (\d+)/(\d+) \| ([\d.]+) \| ([\d.]+) \|", led)
    rows.append(("Static physical", (int(m[1]), int(m[3]), round(float(m[10]) * EV_H)),
                 (s["detected"], s["top1"], round(s["extras_per_event_h"] * EV_H)), r["static"]["normal_alarms"], sum(r["static"]["per_record"])))
    names = {"ML": "Trees, phasor changes", "FIS": "Trees, signatures", "ML+": "Trees, phasor changes, more noise", "FIS+": "Trees, signatures, more noise"}
    for k, nm in names.items():
        a = r[k]["f01_test"]["summary"]; b = r[k]["second_plant"]["summary"]
        rows.append((nm, (a["detected"], a["top1"], round(a["extras_per_event_h"] * EV_H)),
                     (b["detected"], b["top1"], round(b["extras_per_event_h"] * EV_H)), r[k]["second_plant"]["normal_alarms"], sum(r[k]["second_plant"]["per_record"])))
    pc = BS + "%"
    L = [f"{BS}begin{{table}}[t]{BS}centering{BS}scriptsize{BS}setlength{{{BS}tabcolsep}}{{1.5pt}}",
         f"{BS}caption{{Transfer to records simulated with a different plant (classical machines, droop governors, no excitation), built from the same 12 event schedules and passed through the same PMU operator and noise. Detected events, events located at the source (Top-1) and alarms matching no event, out of 72 events, for the original cohort and the new plant. The last columns give normal-record alarms and records with all six events located, out of 12. The dynamic bank needs per-record banks built with the original plant solver and was not run on these records. The two ``more noise'' learners were trained on four extra noise draws per training record.}}",
         f"{BS}label{{tab:second-plant}}", f"{BS}begin{{tabular}}{{lccccccc}}{BS}toprule",
         f" & {BS}multicolumn{{3}}{{c}}{{Original cohort}} & {BS}multicolumn{{3}}{{c}}{{Second plant}} & {BS}multicolumn{{1}}{{c}}{{Records}} {BS}{BS}",
         f"Method & Det. & Top-1 & Extras & Det. & Top-1 & Extras & (of 12) {BS}{BS}{BS}midrule"]
    for nm, a, b, fa, k in rows:
        L.append(f"{nm} & {a[0]} & {a[1]} & {a[2]} & {b[0]} & {b[1]} & {b[2]} & {k} {BS}{BS}")
    L.append(f"{BS}bottomrule{BS}end{{tabular}}{BS}end{{table}}")
    (ROOT / "tables/generated/second_plant.tex").write_text("\n".join(L) + "\n")
    best = max(x[2][1] for x in rows); worstex = min(x[2][2] for x in rows)
    mac = {"SPBestTop": str(best), "SPStaticTop": str(rows[0][2][1]), "SPStaticOrig": str(rows[0][1][1]),
           "SPRecordsOK": str(max(x[4] for x in rows)), "SPNormalAlarms": str(sum(x[3] for x in rows)),
           "SPExtrasLo": str(min(x[2][2] for x in rows[1:])), "SPExtrasHi": str(max(x[2][2] for x in rows[1:])),
           "SPDrop": str(max(x[1][1] - x[2][1] for x in rows[1:]))}
    (ROOT / "generated/revision_secondplant_macros.tex").write_text(
        "% generated by scripts/import_second_plant.py\n" + "".join(f"{BS}newcommand{{{BS}{k}}}{{{v}}}\n" for k, v in mac.items()))
    print(rows); print(mac)


if __name__ == "__main__":
    main()
