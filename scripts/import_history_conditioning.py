"""Import the history-conditioning study (reduced plant, eight stress cells, RAW0001 check).

Reads experiments/history_conditioning/results and writes
  generated/revision_history_macros.tex
  tables/generated/history_conditioning.tex
No number is typed by hand.
"""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "experiments/history_conditioning/results"
BS = chr(92)


def main() -> None:
    d = json.loads((RES / "TEST_RESULTS.json").read_text())
    raw = json.loads((RES / "RAW0001_VALIDATION.json").read_text())
    allc = [d[f"C{i}"] for i in range(1, 11)]
    cells = allc[:8]; ext = allc[8:]
    certs = [c["cert"][k]["certified"] for c in allc for k in ("N", "Q", "R1")]
    flips = sum(c["cert"][k]["flips_certified"] for c in allc for k in ("N", "Q", "R1"))
    costN = sum(c["cost"]["N"] for c in cells) / 8
    costF = sum(c["cost"]["F"] for i, c in enumerate(cells) if i != 4) / 7          # cell with the 0.5-s window is shorter
    best_gain = max(c["cmp"]["M-F"]["dacc"] for c in allc)
    worst_gain = min(c["cmp"]["M-F"]["dacc"] for c in allc)
    n = cells[0]["meta"]["seeds"][2]
    expl = 1 - raw["chi2_all"]["7"] / raw["chi2_null"]
    m = {"HHCells": "8", "HHExtCells": "2", "HHWorstGain": f"{-worst_gain * 100:.1f}",
         "HHExtAErrLo": f"{min(c['A_err'] for c in ext) * 100:.1f}", "HHExtAErrHi": f"{max(c['A_err'] for c in ext) * 100:.1f}",
         "HHExtNLL": f"{ext[0]['cmp']['M-F']['dnll']:.1f}", "HHScenarios": str(n),
         "HHMaxAErr": f"{max(c['A_err'] for c in cells) * 100:.1f}",
         "HHNominalMs": f"{costN:.1f}", "HHPlantMs": f"{costF:.0f}",
         "HHQuadMs": f"{sum(c['cost']['QA'] for i, c in enumerate(cells) if i != 4) / 7 / 1000:.1f}",
         "HHCertMin": f"{min(certs) * 100:.0f}", "HHCertMax": f"{max(certs) * 100:.0f}", "HHCertFlips": str(flips),
         "HHBestGain": f"{best_gain * 100:.1f}",
         "HHRawRank": str(raw["bus7_rank_all"]), "HHRawLoads": str(raw["loads"]), "HHRawExplained": f"{expl * 100:.1f}"}
    (ROOT / "generated/revision_history_macros.tex").write_text(
        "% generated by scripts/import_history_conditioning.py\n" + "".join(f"{BS}newcommand{{{BS}{k}}}{{{v}}}\n" for k, v in m.items()))
    names = "ABCDEFGHIJ"
    L = [f"{BS}begin{{table*}}[t]{BS}centering{BS}footnotesize{BS}setlength{{{BS}tabcolsep}}{{3pt}}",
         f"{BS}caption{{Source accuracy of five predictors in ten stress cells ({n} scenarios each; mismatch is the relative error of the inertia, and the damping is detuned twice as much; cells I and J use a previous severity of 30--60{BS}%, a new source 0.2\,s after the previous one ends, and fresh seeds). Nominal: equilibrium signature on the recentered baseline; plug-in: nonlinear plant at the estimated previous severity; marginalized: plug-in with the previous severity integrated out; quadrature: the same by seven-node quadrature. The last column is the paired accuracy difference marginalized minus plug-in with its 95{BS}% bootstrap interval, in percentage points.}}",
         f"{BS}label{{tab:history-conditioning}}",
         f"{BS}begin{{tabular}}{{cccccccccc}}{BS}toprule",
         f"Cell & Noise & History & Mismatch & Window & Nominal & Plug-in & Marg. & Quad. & Marg.$-$plug-in {BS}{BS}",
         ""]
    pc = BS + "%"
    L[-1] = f" & factor & (s) & ({pc}) & (s) & ({pc}) & ({pc}) & ({pc}) & ({pc}) & (pp) {BS}{BS}{BS}midrule"
    for i, c in enumerate(allc):
        if i == 8: L.append(f"{BS}midrule")
        mt = c["meta"]; a = c["acc"]; cm = c["cmp"]["M-F"]
        hist = "6.5" if mt["th"] > 9 else f"{mt['th']:g}"
        L.append(f"{names[i]} & {mt['scale']:g} & {hist} & {mt['mism'] * 100:.0f} & {mt['W']:g} & {a['N'] * 100:.1f} & {a['F'] * 100:.1f} & {a['M'] * 100:.1f} & {a['QA'] * 100:.1f} & "
                 f"{cm['dacc'] * 100:+.1f} [{cm['ci'][0] * 100:+.1f}, {cm['ci'][1] * 100:+.1f}] {BS}{BS}")
    L += [f"{BS}bottomrule{BS}end{{tabular}}{BS}end{{table*}}"]
    (ROOT / "tables/generated/history_conditioning.tex").write_text("\n".join(L) + "\n")
    print(json.dumps(m, indent=1))


if __name__ == "__main__":
    main()
